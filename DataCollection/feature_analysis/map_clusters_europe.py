#!/usr/bin/env python3
"""
Single cluster map with Europe background in EPSG:3035.

Input:
  clustered CSV generated by cluster_tiles.py, e.g.
  analysis_results/gain_clusters/all_valid_clustered_tiles.csv

The script reads each tile's metadata.json and uses the projected bounds:
  x_min_m, y_min_m, x_max_m, y_max_m
and plots the tiles in EPSG:3035.

Background:
  Natural Earth country polygons, filtered to Europe and reprojected to EPSG:3035.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import geopandas as gpd
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from shapely.geometry import box

PROJECTED_CRS = "EPSG:3035"


def read_tile_metadata(tile_dir: Path) -> dict:
    meta_path = tile_dir / "metadata.json"
    if not meta_path.is_file():
        return {}

    try:
        with meta_path.open() as f:
            data = json.load(f)
    except Exception:
        return {}

    bounds = data.get("bounds") or {}
    return {
        "tile_id": data.get("tile_id", tile_dir.name),
        "x_min_m": bounds.get("x_min_m"),
        "y_min_m": bounds.get("y_min_m"),
        "x_max_m": bounds.get("x_max_m"),
        "y_max_m": bounds.get("y_max_m"),
    }


def load_cluster_table(cluster_csv: Path, tiles_dir: Path) -> pd.DataFrame:
    if not cluster_csv.is_file():
        raise FileNotFoundError(f"Cluster CSV not found: {cluster_csv}")

    df = pd.read_csv(cluster_csv)
    required = {"tile_id", "cluster"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Cluster CSV missing required columns: {sorted(missing)}")

    df = df[["tile_id", "cluster"]].dropna().copy()
    df["tile_id"] = df["tile_id"].astype(str)

    bounds_rows = []
    for _, row in df.iterrows():
        tile_dir = tiles_dir / row["tile_id"]
        meta = read_tile_metadata(tile_dir)

        # Keep the values even if the tile has no projected bounds.
        bounds = {
            "tile_id": row["tile_id"],
            "cluster": row["cluster"],
            "x_min_m": meta.get("x_min_m"),
            "y_min_m": meta.get("y_min_m"),
            "x_max_m": meta.get("x_max_m"),
            "y_max_m": meta.get("y_max_m"),
        }
        bounds_rows.append(bounds)

    merged = pd.DataFrame(bounds_rows)
    merged = df.merge(merged, on=["tile_id", "cluster"], how="left")
    merged = merged.dropna(subset=["x_min_m", "y_min_m", "x_max_m", "y_max_m"]).copy()

    if merged.empty:
        raise ValueError(
            "No tile bounds found. Check that each tile has metadata.json "
            "with x_min_m/y_min_m/x_max_m/y_max_m."
        )

    return merged


def load_europe_background() -> gpd.GeoDataFrame:
    url = (
        "https://naturalearth.s3.amazonaws.com/110m_cultural/"
        "ne_110m_admin_0_countries.zip"
    )
    world = gpd.read_file(url)

    # Use all countries and keep Turkey; don't filter to Europe by continent.
    return world.to_crs(PROJECTED_CRS)


def plot_one_map(
    cluster_df: pd.DataFrame,
    europe: gpd.GeoDataFrame,
    out_path: Path,
) -> None:
    # Tile centroids in projected coordinates.
    x = (cluster_df["x_min_m"] + cluster_df["x_max_m"]) / 2
    y = (cluster_df["y_min_m"] + cluster_df["y_max_m"]) / 2

    clusters = sorted(cluster_df["cluster"].astype(str).unique(), key=lambda s: str(s))
    cluster_to_code = {cluster: i for i, cluster in enumerate(clusters)}
    codes = cluster_df["cluster"].astype(str).map(cluster_to_code).to_numpy()

    cmap = plt.get_cmap("tab20", len(clusters))
    norm = plt.Normalize(vmin=0, vmax=max(len(clusters) - 1, 1))

    fig, ax = plt.subplots(figsize=(13, 11))

    europe.plot(
        ax=ax,
        color="#e9eef5",
        edgecolor="#7b7b7b",
        linewidth=0.6,
        zorder=1,
    )

    sc = ax.scatter(
        x,
        y,
        c=codes,
        cmap=cmap,
        norm=norm,
        s=170,
        edgecolors="black",
        linewidths=0.7,
        alpha=0.95,
        zorder=3,
    )

    # Zoom to the tiles, not to all of Europe.
    xmin = float(cluster_df["x_min_m"].min())
    xmax = float(cluster_df["x_max_m"].max())
    ymin = float(cluster_df["y_min_m"].min())
    ymax = float(cluster_df["y_max_m"].max())

    pad_x = max((xmax - xmin) * 0.12, 50_000)
    pad_y = max((ymax - ymin) * 0.12, 50_000)
    ax.set_xlim(xmin - pad_x, xmax + pad_x)
    ax.set_ylim(ymin - pad_y, ymax + pad_y)

    ax.set_aspect("equal", adjustable="box")
    ax.set_facecolor("#d9edf9")

    cbar = fig.colorbar(
        sc,
        ax=ax,
        ticks=np.arange(len(clusters)),
        fraction=0.03,
        pad=0.03,
    )
    cbar.ax.set_yticklabels([str(cluster) for cluster in clusters])
    cbar.set_label("Cluster")

    ax.set_title(f"Tile clusters in Europe (EPSG:3035) — {len(clusters)} clusters")
    ax.set_xlabel("Easting (m)")
    ax.set_ylabel("Northing (m)")

    fig.tight_layout()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=220, bbox_inches="tight")
    plt.close(fig)
    print(f"Saved map: {out_path}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Plot tile clusters on Europe background in EPSG:3035."
    )
    parser.add_argument(
        "--input",
        type=Path,
        required=True,
        help="Clustered CSV with tile_id and cluster columns.",
    )
    parser.add_argument(
        "--tiles-dir",
        type=Path,
        required=True,
        help="Parent directory containing tile_* folders.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("tile_cluster_map_europe.png"),
        help="Output PNG path.",
    )
    args = parser.parse_args()

    cluster_df = load_cluster_table(args.input, args.tiles_dir)
    europe = load_europe_background()
    plot_one_map(cluster_df, europe, args.out)


if __name__ == "__main__":
    main()
